const { v4: uuidv4 } = require('uuid');
const localStore = require('./localStore');
const { invokeLocalLlama, HEALTHCARE_GUARDRAILS } = require('./aiEngineService');
const { createNotification } = require('./notificationService');

/**
 * Submit a health question and generate AI draft
 */
async function submitQuestion(userId, question) {
  const prompt = `A patient asks: "${question}"

Provide a concise, patient-friendly response with safe general guidance only. Do not diagnose. If the user asks for medicine, explain that you cannot prescribe, mention common non-prescription comfort measures in general terms only when appropriate, and recommend consulting a qualified clinician or pharmacist.`;
  const aiResponse = await invokeLocalLlama(prompt, HEALTHCARE_GUARDRAILS);
  const requiresReview = process.env.REQUIRE_CLINICIAN_REVIEW !== 'false';

  const draftId = uuidv4();
  const draft = {
    draftId,
    userId,
    question,
    aiResponse: aiResponse.text,
    model: aiResponse.model,
    status: requiresReview ? 'pending_review' : 'approved',
    reviewedBy: requiresReview ? null : 'LOCAL_AI',
    reviewedAt: requiresReview ? null : new Date().toISOString(),
    createdAt: new Date().toISOString()
  };

  await localStore.insert('chatDrafts', draft);

  if (requiresReview) {
    await createNotification({
      userId: 'CLINICIAN_POOL',
      type: 'system_update',
      message: `New chat draft pending review from patient ${userId}`
    });
  }

  return {
    draftId,
    status: draft.status,
    aiResponse: draft.aiResponse,
    model: draft.model,
    reviewedAt: draft.reviewedAt,
    message: requiresReview
      ? 'Local AI answered immediately. A doctor can review and update this response.'
      : 'Generated by local Llama 3. Please consult a qualified healthcare professional for medical concerns.'
  };
}

/**
 * Get draft response status
 */
async function getDraftResponse(draftId, userId) {
  const draft = await localStore.findById('chatDrafts', 'draftId', draftId);

  if (!draft) {
    throw new Error('Draft not found');
  }

  if (draft.userId !== userId) {
    throw new Error('Unauthorized access to draft');
  }

  if (draft.status === 'approved') {
    return {
      status: 'approved',
      question: draft.question,
      response: draft.aiResponse,
      editedResponse: draft.editedResponse || null,
      clinicianNotes: draft.clinicianNotes || null,
      reviewedAt: draft.reviewedAt,
      reviewedBy: draft.reviewedBy
    };
  }

  if (draft.status === 'rejected') {
    return {
      status: 'rejected',
      message: 'The response was rejected by the clinician. A new draft is being generated.'
    };
  }

  return {
    status: 'pending_review',
    question: draft.question,
    response: draft.aiResponse,
    model: draft.model,
    message: 'Your response is awaiting clinician review.'
  };
}

/**
 * Review and approve/reject draft
 */
async function reviewDraft(draftId, clinicianId, action, editedResponse = null, clinicianNotes = null) {
  if (action !== 'approve' && action !== 'reject') {
    throw new Error('Action must be "approve" or "reject"');
  }

  const draft = await localStore.findById('chatDrafts', 'draftId', draftId);

  if (!draft) {
    throw new Error('Draft not found');
  }

  if (action === 'approve') {
    const updates = {
      status: 'approved',
      reviewedBy: clinicianId,
      reviewedAt: new Date().toISOString()
    };

    if (editedResponse) {
      updates.editedResponse = editedResponse;
    }

    if (clinicianNotes) {
      updates.clinicianNotes = clinicianNotes;
    }

    await localStore.updateById('chatDrafts', 'draftId', draftId, updates);

    await createNotification({
      userId: draft.userId,
      type: 'system_update',
      message: 'Your health question has been answered. Check your chat for the response.'
    });

    return { message: 'Draft approved and delivered to patient' };
  }

  await localStore.updateById('chatDrafts', 'draftId', draftId, {
    status: 'rejected',
    reviewedBy: clinicianId,
    reviewedAt: new Date().toISOString()
  });

  await submitQuestion(draft.userId, draft.question);

  return { message: 'Draft rejected. New draft generated for review.' };
}

/**
 * Get all pending drafts for clinician review
 */
async function getPendingDrafts() {
  const drafts = await localStore.list(
    'chatDrafts',
    draft => draft.status === 'pending_review',
    { sortBy: 'createdAt', desc: true }
  );

  return {
    drafts,
    count: drafts.length
  };
}

/**
 * Get user's chat history
 */
async function getChatHistory(userId) {
  const chats = await localStore.list(
    'chatDrafts',
    draft => draft.userId === userId,
    { sortBy: 'createdAt', desc: true }
  );

  return {
    chats,
    count: chats.length
  };
}

module.exports = {
  submitQuestion,
  getDraftResponse,
  reviewDraft,
  getPendingDrafts,
  getChatHistory
};
